export function applyProductCopy<T extends {
  slug: string;
  shortDescription: string;
  description: string;
  displayTitle?: string;
  tagline?: string;
  benefits?: string[];
  howToUse?: HowToSection[];
  disclaimer?: string;
  adHook?: string;
}>(product: T): T {
  const copy = productCopyBySlug[product.slug];
  if (!copy) return product;
  return {
    ...product,
    displayTitle: copy.displayTitle,
    tagline: copy.tagline,
    shortDescription: copy.shortDescription,
    description: copy.description,
    benefits: copy.benefits.length ? copy.benefits : product.benefits,
    howToUse: copy.howToUse.length ? copy.howToUse : product.howToUse,
    disclaimer: copy.disclaimer ?? product.disclaimer,
    adHook: copy.adHook ?? product.adHook
  };
}
